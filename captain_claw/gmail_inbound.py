@dataclass(frozen=True)
class Inbound:
    """One Gmail message as the auto-reply reads it.

    ``headers`` is ``payload.headers`` top to bottom with duplicates kept;
    folded values are unfolded. Addresses are lowercased. ``text`` is the
    text/plain body (the text/html one flattened when there is no plain part),
    clipped to :data:`MAX_TEXT_CHARS`. ``attachment_names`` lists real
    attachments only: a Content-ID image under 100 KB is a signature picture
    and is left out. A forwarded message is an attachment, never body text.
    """

    message_id: str
    thread_id: str
    label_ids: frozenset[str]
    internal_ms: int
    headers: tuple[tuple[str, str], ...]
    from_header_count: int
    from_addrs: tuple[str, ...]
    from_name: str
    reply_to: tuple[str, ...]
    to_addrs: tuple[str, ...]
    cc_addrs: tuple[str, ...]
    subject: str
    has_subject: bool
    text: str
    attachment_names: tuple[str, ...]
    content_type: str


def _blank(message_id: str = "", thread_id: str = "",
           label_ids: frozenset[str] = frozenset(), internal_ms: int = 0) -> Inbound:
    """An :class:`Inbound` with nothing readable in it. It fails check 1 or 3."""
    return Inbound(
        message_id=message_id, thread_id=thread_id, label_ids=label_ids,
        internal_ms=internal_ms, headers=(), from_header_count=0, from_addrs=(),
        from_name="", reply_to=(), to_addrs=(), cc_addrs=(), subject="",
        has_subject=False, text="", attachment_names=(), content_type="",
    )


