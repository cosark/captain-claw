# An attribution line is short and carries a date, so a sentence that merely
# starts with "On" and ends with "wrote:" is left alone.
_ATTRIBUTION_MAX_CHARS = 300
_DIGIT_RE = re.compile(r"\d")
_EN_WROTE_RE = re.compile(r"^\s*On\s.*\bwrote\s*:\s*$", re.IGNORECASE)
# HR: Thunderbird "Dana 13. 10. 2026. u 10:15, Ana je napisala:", Gmail
# "pon, 13. lis 2026. u 10:15 Ana <ana@x.hr> napisala je:".
_HR_WROTE_RE = re.compile(
    r"^\s*(?:Dana\s.*\bnapisa(?:o|la)(?:\s+je)?|\S.*\bnapisa(?:o|la)\s+je)\s*:\s*$",
    re.IGNORECASE)
# Where a wrapped attribution's first line can start.
_ATTRIBUTION_START_RE = re.compile(
    r"^\s*(?:On|Dana|pon|uto|sri|čet|cet|pet|sub|ned)\b", re.IGNORECASE)
_ORIGINAL_RE = re.compile(
    r"^\s*-{3,}\s*(?:Original Message|Izvorna poruka|Originalna poruka)\s*-{3,}\s*$",
    re.IGNORECASE)
# Outlook's quoted header block: "From: …" with "Sent: …" just below.
_OUTLOOK_FROM_RE = re.compile(r"^\s*(?:From|Od|Šalje)\s*:\s*\S", re.IGNORECASE)
_OUTLOOK_SENT_RE = re.compile(r"^\s*(?:Sent|Poslano)\s*:\s*\S", re.IGNORECASE)


def _attribution(line: str) -> bool:
    return (len(line) <= _ATTRIBUTION_MAX_CHARS and bool(_DIGIT_RE.search(line))
            and bool(_EN_WROTE_RE.match(line) or _HR_WROTE_RE.match(line)))


def _quote_starts(lines: list[str], i: int) -> bool:
    """Whether the quoted part of the message starts at ``lines[i]``."""
    line = lines[i]
    if _ORIGINAL_RE.match(line) or _attribution(line):
        return True
    nxt = lines[i + 1] if i + 1 < len(lines) else ""
    if nxt and _ATTRIBUTION_START_RE.match(line) and _attribution(f"{line} {nxt.strip()}"):
        return True    # an attribution wrapped over two lines
    if _OUTLOOK_FROM_RE.match(line):
        return any(_OUTLOOK_SENT_RE.match(x) for x in lines[i + 1:i + 4])
    return False


def strip_quoted(text: str) -> str:
    """*text* without what it quotes: ``>`` lines are dropped, and everything
    from the first "On … wrote:", "-----Original Message-----", "Dana …
    napisao/la:" (or Gmail's "… napisao/la je:") or Outlook "From:/Sent:"
    block is cut. Never raises; "" for anything but text."""
    try:
        if not isinstance(text, str):
            return ""
        lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
        kept: list[str] = []
        for i, line in enumerate(lines):
            if _quote_starts(lines, i):
                break
            if line.lstrip().startswith(">"):
                continue
            kept.append(line)
        return "\n".join(kept).strip()
    except Exception:
        return ""


