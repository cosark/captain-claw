_OOO_SUBJECT_RE = re.compile(
    r"\b(?:automatic\s+(?:reply|response)|auto[\s_-]?(?:reply|response)"
    r"|out\s+of\s+(?:the\s+)?office|automatski\s+odgovor"
    r"|odsut(?:an|na|ni|ne|no|nost\w*))\b",
    re.IGNORECASE)
_FIRST_TOKEN_RE = re.compile(r"[;\s(]")


def _first_token(value: str) -> str:
    return _FIRST_TOKEN_RE.split(value.strip().lower(), 1)[0]


# Consumer Gmail ignores dots in the local part, and googlemail.com is the
# same mailbox as gmail.com.
_GMAIL_DOMAINS = frozenset({"gmail.com", "googlemail.com"})


def own_address_key(address: Any) -> str:
    """The mailbox *address* is delivered to, for matching it against own
    addresses only: lowercased, without a ``+tag`` (Gmail and Workspace
    subaddressing), and for gmail.com / googlemail.com without dots, read as
    gmail.com. ``Owner.Inbox+tag@GoogleMail.com`` and ``ownerinbox@gmail.com``
    are the same key; ``ja.ne@company.example`` stays as it is (Workspace
    addresses are dot-sensitive). Never a recipient: a reply goes to the exact
    verified From address. "" for anything but text."""
    if not isinstance(address, str):
        return ""
    addr = address.strip().lower()
    local, at, domain = addr.rpartition("@")
    if not at or not local:
        return addr
    local = local.split("+", 1)[0] or local
    if domain in _GMAIL_DOMAINS:
        local = local.replace(".", "") or local
        domain = "gmail.com"
    return f"{local}@{domain}"


def _own_set(own_addresses: Any) -> frozenset[str]:
    """Own addresses as a set of :func:`own_address_key` keys. A single
    string is one address."""
    if isinstance(own_addresses, str):
        own_addresses = [own_addresses]
    out: set[str] = set()
    for entry in own_addresses or ():
        if isinstance(entry, str):
            out.update(own_address_key(a) for a in gmail_compose.parse_addresses(entry))
    return frozenset(out)


def sender_address(inb: Inbound) -> str:
    """The From address when check 3's shape holds (exactly one From header
    holding exactly one usable address), lowercased; "" otherwise. After
    :func:`sender_authenticated` passes, this is the verified sender, the
    only address an auto-reply may go to."""
    try:
        if inb.from_header_count != 1 or len(inb.from_addrs) != 1:
            return ""
        addr = inb.from_addrs[0]
        if gmail_compose.invalid_recipients(addr):
            return ""
        return addr
    except Exception:
        return ""


def _labels_ok(inb: Inbound) -> bool:
    return "INBOX" in inb.label_ids and not (SKIP_LABELS & inb.label_ids)


def _automated_sender(inb: Inbound) -> bool:
    raw = " ".join(_values(inb.headers, "From")).lower()
    if any(bit in raw for bit in AUTOMATED_SENDER_BITS):
        return True
    for addr in inb.from_addrs:
        local = addr.rpartition("@")[0]
        if local in AUTOMATED_LOCAL_PARTS or local.startswith("bounce"):
            return True
    return False


def _auto_or_list(inb: Inbound) -> bool:
    for name, value in inb.headers:
        key = name.strip().lower()
        if key in LIST_HEADERS:
            return True
        if key == "auto-submitted" and _first_token(value) != "no":
            return True
        if key == "precedence" and _first_token(value) in BULK_PRECEDENCE:
            return True
        if key == "return-path" and _SPACES_RE.sub("", value) == "<>":
            return True
    if inb.content_type in REPORT_CONTENT_TYPES:
        return True
    return bool(_OOO_SUBJECT_RE.search(inb.subject))


def auto_reply_blockers(inb: Inbound, *, own_addresses: Iterable[str]) -> list[str]:
    """Every loop and bulk guard *inb* fails, in check order; empty when none.

    * ``labels`` (check 1): no ``INBOX``, or one of :data:`SKIP_LABELS`;
    * ``from_invalid`` / ``own_mail`` (check 3): not exactly one From header
      with one usable address / that address is one of *own_addresses*
      (compared by :func:`own_address_key`, so a ``+tag`` or dotted Gmail
      form of an own address is own mail too);
    * ``automated_sender`` (check 4): :data:`AUTOMATED_SENDER_BITS` in From,
      or a machine local part;
    * ``auto_or_list`` (check 5): ``Auto-Submitted`` other than ``no``, a bulk
      ``Precedence``, a list or auto-responder header, ``Return-Path: <>``, a
      delivery report, or an out-of-office subject (EN/HR).

    :data:`CHECK_ERROR` alone when the check itself failed.
    """
    try:
        own = _own_set(own_addresses)
        out: list[str] = []
        if not _labels_ok(inb):
            out.append("labels")
        sender = sender_address(inb)
        if not sender:
            out.append("from_invalid")
        elif own_address_key(sender) in own:
            out.append("own_mail")
        if _automated_sender(inb):
            out.append("automated_sender")
        if _auto_or_list(inb):
            out.append("auto_or_list")
        return out
    except Exception:
        return [CHECK_ERROR]


def reply_to_ok(inb: Inbound) -> bool:
    """Check 7: no Reply-To, or exactly one Reply-To header holding exactly
    one address, the From address (case-folded). A contact form that relies on
    Reply-To is skipped, never answered at the Reply-To address."""
    try:
        values = _values(inb.headers, "Reply-To")
        if not values:
            return True
        if len(values) != 1:
            return False
        pairs = _pairs(values)
        sender = sender_address(inb)
        return len(pairs) == 1 and bool(sender) and pairs[0][1].casefold() == sender.casefold()
    except Exception:
        return False


def addressed_to_owner(inb: Inbound, own_addresses: Iterable[str]) -> str:
    """Check 8: "" when an own address is in To or Cc and To plus Cc hold at
    most :data:`MAX_ADDRESSED` addresses; ``not_addressed_to_me`` (Bcc, list
    delivery, or no own addresses known), else ``group_mail``. Own addresses
    match by :func:`own_address_key`: Gmail delivers ``owner+tag@``, the
    dotless and the googlemail.com forms to the same inbox."""
    try:
        own = _own_set(own_addresses)
        addressed = list(dict.fromkeys(inb.to_addrs + inb.cc_addrs))
        if not own or not any(own_address_key(a) in own for a in addressed):
            return "not_addressed_to_me"
        if len(addressed) > MAX_ADDRESSED:
            return "group_mail"
        return ""
    except Exception:
        return "not_addressed_to_me"


def body_blocker(inb: Inbound) -> str:
    """Check 9: "" when the text left after :func:`strip_quoted` is 1 to
    :data:`MAX_BODY_CHARS` characters, else ``empty`` / ``too_long``."""
    try:
        body = strip_quoted(inb.text).strip()
        if not body:
            return "empty"
        return "too_long" if len(body) > MAX_BODY_CHARS else ""
    except Exception:
        return "empty"


def iso_to_ms(value: Any) -> int:
    """An ISO 8601 timestamp (``enabled_at``) as epoch milliseconds. A naive
    one is UTC. 0 for anything unreadable, which :func:`age_blocker` treats
    as "not enabled"."""
    try:
        dt = datetime.fromisoformat(str(value).strip())
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=UTC)
        return int(dt.timestamp() * 1000)
    except Exception:
        return 0


def age_blocker(inb: Inbound, *, enabled_at_ms: int, now_ms: int | None = None,
                max_age_s: int = MAX_AGE_S) -> str:
    """Check 2: ``before_enable`` when the message arrived before auto-reply
    was enabled (or either time is unknown), ``stale`` when it is older than
    *max_age_s* at *now_ms*, else "". The engine re-checks with 90 minutes
    right before a send."""
    try:
        # int() refuses NaN and infinities, which would compare as "fine".
        numeric = isinstance(enabled_at_ms, (int, float)) and not isinstance(enabled_at_ms, bool)
        enabled = int(enabled_at_ms) if numeric else 0
        received = int(inb.internal_ms)
        if received <= 0 or enabled <= 0 or received < enabled:
            return "before_enable"
        now = int(time.time() * 1000) if now_ms is None else int(now_ms)
        return "stale" if now - received > int(max_age_s * 1000) else ""
    except Exception:
        return "before_enable"


def prefilter(inb: Inbound, *, own_addresses: Iterable[str], enabled_at_ms: int,
              now_ms: int | None = None, max_age_s: int = MAX_AGE_S) -> tuple[str, str]:
    """The design's checks 1–9, cheapest first, as ``(code, detail)``.

    ``code`` is "" when every check passed, else the first failure, one of
    :data:`PREFILTER_CODES` (or :data:`CHECK_ERROR`), recorded as
    ``skipped/<code>``. ``detail`` is :func:`sender_authenticated`'s reason:
    the failure for ``unauthenticated``, the verified method (``dmarc`` or
    ``dkim``) on a pass, "" otherwise. Checks 10 (caps) and 11 (human
    takeover) need the ledger and the thread; the engine runs them after.
    """
    try:
        own = _own_set(own_addresses)
        if not _labels_ok(inb):
            return "labels", ""
        age = age_blocker(inb, enabled_at_ms=enabled_at_ms, now_ms=now_ms, max_age_s=max_age_s)
        if age:
            return age, ""
        blockers = auto_reply_blockers(inb, own_addresses=own)
        if blockers:
            return blockers[0], ""
        ok, reason = sender_authenticated(inb)
        if not ok:
            return "unauthenticated", reason
        if not reply_to_ok(inb):
            return "reply_to_divergent", ""
        addressed = addressed_to_owner(inb, own)
        if addressed:
            return addressed, ""
        body = body_blocker(inb)
        if body:
            return body, ""
        return "", reason
    except Exception:
        return CHECK_ERROR, ""


