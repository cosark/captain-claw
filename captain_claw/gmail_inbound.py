_LINE_BREAK_RE = re.compile(r"\r\n|\r|\n")
_HEADER_CONTROL_RE = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")
# Control, zero-width and bidi characters: never part of a name or subject a
# person reads, and the sender could hide words with them.
_DISPLAY_CONTROL_RE = re.compile(
    r"[\x00-\x1f\x7f-\x9f\u200b-\u200f\u202a-\u202e\u2060-\u2069\ufeff]")
_SPACES_RE = re.compile(r"\s+")
_CHARSET_RE = re.compile(r"charset\s*=\s*\"?([A-Za-z0-9_.:+-]+)", re.IGNORECASE)
_ENCODED_WORD_RE = re.compile(r"=\?[^?\s]+\?[QqBb]\?[^?\s]*\?=")
_ADJACENT_WORDS_RE = re.compile(r"\?=\s+(?==\?[^?\s]+\?[QqBb]\?)")


def _text(value: Any) -> str:
    return value if isinstance(value, str) else ""


def _as_int(value: Any) -> int:
    """An int, or a string of ASCII digits (Gmail's ``internalDate``), as an
    int; 0 for anything else."""
    if isinstance(value, bool):
        return 0
    if isinstance(value, int):
        return value
    if isinstance(value, str):
        digits = value.strip()
        if digits.isascii() and digits.isdigit() and len(digits) <= 19:
            return int(digits)
    return 0


def _header_value(value: str) -> str:
    """A header value as one line: folding line breaks become spaces, other
    control characters too."""
    value = _LINE_BREAK_RE.sub(" ", value[:_MAX_HEADER_CHARS])
    return _HEADER_CONTROL_RE.sub(" ", value)


def _headers(raw: Any) -> tuple[tuple[str, str], ...]:
    """``payload.headers`` as ``(name, value)`` pairs, top to bottom, with
    duplicates kept. Entries without a name are dropped."""
    if not isinstance(raw, list):
        return ()
    out: list[tuple[str, str]] = []
    for h in raw[:_MAX_HEADERS]:
        if not isinstance(h, dict):
            continue
        name = _text(h.get("name")).strip()
        if name:
            out.append((name, _header_value(_text(h.get("value")))))
    return tuple(out)


def _values(headers: Iterable[tuple[str, str]], name: str) -> list[str]:
    key = name.lower()
    return [v for n, v in headers if n.strip().lower() == key]


def header_values(inb: Inbound, name: str) -> list[str]:
    """Every value of header *name* (case-insensitive), top to bottom. The
    engine's human-takeover check reads ``Auto-Submitted`` on thread
    messages with it."""
    try:
        return _values(inb.headers, name)
    except Exception:
        return []


def _decode_word(match: re.Match) -> str:
    try:
        (raw, charset), = email.header.decode_header(match.group(0))
        if isinstance(raw, bytes):
            return raw.decode(charset or "ascii", errors="replace")
        return raw
    except Exception:
        return match.group(0)


def _decode_words(value: str) -> str:
    """RFC 2047 encoded words (``=?utf-8?q?…?=``) decoded; the value as it
    is when there are none or they don't decode. email.header mangles
    non-ASCII text next to an encoded word (Gmail may hand us either), so a
    value that isn't pure ASCII is decoded one word at a time."""
    if "=?" not in value:
        return value
    if value.isascii():
        try:
            return str(email.header.make_header(email.header.decode_header(value)))
        except Exception:
            return value
    # Whitespace between two adjacent encoded words isn't part of the text.
    value = _ADJACENT_WORDS_RE.sub("?=", value)
    return _ENCODED_WORD_RE.sub(_decode_word, value)


def _display(value: str, limit: int) -> str:
    """Sender-written text a person or a prompt will read: NFC, control and
    invisible characters out, whitespace collapsed, clipped."""
    value = unicodedata.normalize("NFC", value)
    value = _DISPLAY_CONTROL_RE.sub(" ", value)
    return _SPACES_RE.sub(" ", value).strip()[:limit]


def _pairs(values: list[str]) -> list[tuple[str, str]]:
    """``(name, address)`` pairs across header *values*, blanks dropped, so
    "exactly one address" can be counted. email.utils parses strictly: a
    value it can't read comes back as no pairs."""
    if not values:
        return []
    return [(n, a.strip()) for n, a in email.utils.getaddresses(values) if a.strip()]


def _decode_data(data: str, content_type: str) -> str:
    """A part's base64url ``body.data`` as text. UTF-8 first, then the
    declared charset, then UTF-8 with replacement characters."""
    data = data[:_MAX_PART_DATA]
    try:
        raw = base64.urlsafe_b64decode(data + "=" * (-len(data) % 4))
    except Exception:
        return ""
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        pass
    m = _CHARSET_RE.search(content_type)
    if m:
        try:
            info = codecs.lookup(m.group(1))
            # Only real text charsets: a declared punycode / idna / *-escape
            # decodes in quadratic time (or isn't a charset at all).
            if info._is_text_encoding and info.name not in _UNSAFE_CHARSETS:
                return raw.decode(info.name, errors="replace")
        except (LookupError, ValueError, AttributeError):
            pass
    return raw.decode("utf-8", errors="replace")


def _walk(part: Any, texts: list[str], htmls: list[str], names: list[str],
          budget: list[int], depth: int = 0) -> None:
    """Collect the text/plain and text/html bodies and the attachment names
    of one MIME part and its children.

    Which parts are files follows ``GoogleMailTool._extract_parts``: a named
    part with an attachment id, or with inline data that isn't body text (or
    is marked ``Content-Disposition: attachment``); an unnamed leaf that isn't
    text. A forwarded ``message/rfc822`` is a file too, and its text is never
    read as the sender's own.
    """
    if not isinstance(part, dict) or depth > _MAX_DEPTH or budget[0] <= 0:
        return
    budget[0] -= 1
    mime = _text(part.get("mimeType")).strip().lower()
    body = part.get("body") if isinstance(part.get("body"), dict) else {}
    part_headers = _headers(part.get("headers"))
    filename = _display(_text(part.get("filename")), _MAX_NAME_CHARS)
    att_id = _text(body.get("attachmentId"))
    data = _text(body.get("data"))
    children = part.get("parts") if isinstance(part.get("parts"), list) else []
    is_body_text = mime in ("text/plain", "text/html")

    if mime == "message/rfc822":
        is_file = True
    elif filename:
        disposition = next(iter(_values(part_headers, "Content-Disposition")), "")
        is_file = bool(att_id) or bool(
            data and (not is_body_text or disposition.strip().lower().startswith("attachment")))
    else:
        is_file = (
            not children and not is_body_text and not mime.startswith("multipart/")
            and bool(att_id or (data and not mime.startswith("text/")))
        )

    if is_file:
        if (mime.startswith("image/") and _values(part_headers, "Content-ID")
                and _as_int(body.get("size")) < INLINE_IMAGE_MAX_BYTES):
            return
        if len(names) < _MAX_NAMES:
            if not filename:
                if mime == "message/rfc822":
                    filename = "forwarded-message.eml"
                else:
                    ext = (mimetypes.guess_extension(mime) or "") if mime else ""
                    filename = f"attachment-{len(names) + 1}{ext}"
            names.append(filename)
        return

    if data and is_body_text:
        content_type = next(iter(_values(part_headers, "Content-Type")), "")
        decoded = _decode_data(data, content_type)
        if decoded:
            (texts if mime == "text/plain" else htmls).append(decoded)

    for child in children:
        _walk(child, texts, htmls, names, budget, depth + 1)


def parse_message(msg: dict) -> Inbound:
    """A Gmail API message (``format=full``) as an :class:`Inbound`. Never
    raises: what can't be read is left empty, so the checks fail closed."""
    message_id = thread_id = ""
    label_ids: frozenset[str] = frozenset()
    internal_ms = 0
    try:
        if not isinstance(msg, dict):
            return _blank()
        message_id = _text(msg.get("id"))
        thread_id = _text(msg.get("threadId"))
        labels = msg.get("labelIds")
        label_ids = frozenset(
            x for x in (labels if isinstance(labels, list) else []) if isinstance(x, str))
        internal_ms = max(0, _as_int(msg.get("internalDate")))

        payload = msg.get("payload") if isinstance(msg.get("payload"), dict) else {}
        headers = _headers(payload.get("headers"))

        from_values = _values(headers, "From")
        from_pairs = _pairs(from_values)
        from_name = ""
        if len(from_pairs) == 1:
            from_name = _display(_decode_words(from_pairs[0][0]), _MAX_NAME_CHARS)

        subjects = [s for s in _values(headers, "Subject") if s.strip()]
        subject = _display(_decode_words(subjects[0]), _MAX_SUBJECT_CHARS) if subjects else ""

        texts: list[str] = []
        htmls: list[str] = []
        names: list[str] = []
        _walk(payload, texts, htmls, names, [_MAX_PARTS])
        if texts:
            text = "\n".join(texts)
        elif htmls:
            # Bounded before converting: only MAX_TEXT_CHARS of text are kept.
            text = gmail_compose.html_to_text("\n".join(htmls)[:_MAX_HTML_CHARS])
        else:
            text = ""
        text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\x00", "")

        content_type = _text(payload.get("mimeType")).strip().lower()
        if not content_type:
            ct = next(iter(_values(headers, "Content-Type")), "")
            content_type = ct.split(";", 1)[0].strip().lower()

        return Inbound(
            message_id=message_id,
            thread_id=thread_id,
            label_ids=label_ids,
            internal_ms=internal_ms,
            headers=headers,
            from_header_count=len(from_values),
            from_addrs=tuple(a.lower() for _n, a in from_pairs),
            from_name=from_name,
            reply_to=tuple(gmail_compose.parse_addresses(*_values(headers, "Reply-To"))),
            to_addrs=tuple(gmail_compose.parse_addresses(*_values(headers, "To"))),
            cc_addrs=tuple(gmail_compose.parse_addresses(*_values(headers, "Cc"))),
            subject=subject,
            has_subject=bool(subject),
            text=text[:MAX_TEXT_CHARS],
            attachment_names=tuple(names),
            content_type=content_type,
        )
    except Exception as exc:
        _log.debug("gmail_inbound: message %s unreadable: %s", message_id, type(exc).__name__)
        return _blank(message_id, thread_id, label_ids, internal_ms)


