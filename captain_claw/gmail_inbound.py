# Sender authentication (check 6)
# ---------------------------------------------------------------------------

# Gmail's MX hop: "Received: from mail.example.com (…) by mx.google.com with
# ESMTPS id …". Only mail that reached Gmail over SMTP crossed it; an HTTP or
# ESMTPSA submission, or POP3, never did.
_MX_HOP_RE = re.compile(
    r"^from\s+\S[^;]*?\sby\s+mx\.google\.com\s+with\s+(?:UTF8SMTPS?|E?SMTPS?)\s+id\s+\S",
    re.IGNORECASE)
# Gmail's internal hops above it: "Received: by 2002:a05:… with SMTP id …".
_INTERNAL_HOP_RE = re.compile(r"^by\s+\S+\s+with\s+SMTP\s+id\s+\S", re.IGNORECASE)
# What Gmail writes above its MX hop when it delivers a message (both real
# captures, plus Gmail forwarding). Anything else there (DKIM-Signature,
# X-Gm-Message-State, an HTTP submission hop, MIME-Version, From …) was
# written on the way out by whoever submitted the message, so an
# Authentication-Results below it is that submitter's, not Google's.
_GOOGLE_DELIVERY_HEADERS = frozenset({
    "delivered-to", "received", "x-received", "arc-seal", "arc-message-signature",
    "arc-authentication-results", "return-path", "x-google-smtp-source",
    "x-forwarded-to", "x-forwarded-for", "x-forwarded-encrypted",
})
# The envelope sender as Gmail records it in Return-Path: a plain dot-atom
# address, or <> for a bounce. Gmail prints the same sender unescaped inside
# the SPF comment of its Authentication-Results, so one that could close that
# comment or start a result of its own (quotes, parentheses, ;, \, spaces,
# an address literal) is refused even when the results happen to parse.
_RETURN_PATH_RE = re.compile(
    r"^<(?:[A-Za-z0-9!#$%&'*+/=?^_`{|}~.-]+@[A-Za-z0-9](?:[A-Za-z0-9.-]*[A-Za-z0-9])?)?>$")
_METHOD_RE = re.compile(r"^[a-z0-9_-]+(?:/\d+)?$")
_RESULT_RE = re.compile(r"^[a-z0-9_-]+$")
# All a result may hold before its comment: "method=result".
_METHODSPEC_RE = re.compile(r"\s*[a-z0-9_-]+(?:/\d+)?\s*=\s*[a-z0-9_-]+\s*", re.IGNORECASE)
# The one thing Google quotes: a property value that isn't a token
# (header.b="Pli4S9/s"). Nothing inside it is structural.
_QUOTED_VALUE_RE = re.compile(r"\"[A-Za-z0-9!#$%&'*+/=?^_`{|}~.@:-]*\"")
# Results Google writes at most once per header; a second one was injected.
_SINGLE_METHODS = ("dmarc", "spf", "arc")
_DOMAIN_RE = re.compile(
    r"^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+$"
)
_DMARC_FAILS = frozenset({"fail", "temperror", "permerror"})


class _Result(NamedTuple):
    method: str
    result: str
    props: tuple[tuple[str, str], ...]

    def prop(self, key: str) -> str | None:
        """The property's value, "" when absent, None when it appears with
        two different values (an ambiguous result proves nothing)."""
        found = {v for k, v in self.props if k == key}
        if len(found) > 1:
            return None
        return found.pop() if found else ""


def _comment_end(value: str, start: int) -> int:
    """The index just past the comment that opens at ``value[start]``,
    following nested comments, quoted-pairs and quoted strings, so the ``)``
    of a quoted local part doesn't end it. -1 when it never closes."""
    depth = 0
    quoted = False
    i, n = start, len(value)
    while i < n:
        ch = value[i]
        if ch == "\\":
            i += 2
            continue
        if quoted:
            quoted = ch != '"'
        elif ch == '"':
            quoted = True
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if not depth:
                return i + 1
        i += 1
    return -1


def _split_auth_results(value: str) -> list[str] | None:
    """*value* split at its ``;`` with each (comment) dropped, as RFC 8601
    reads it, but only in the shape Google writes; None (malformed) for
    anything else.

    Gmail prints the envelope sender (the sender's choice: RFC 5321 lets a
    quoted local part hold ``( ) ; =`` and spaces) unescaped inside its SPF
    comment and again as ``smtp.mailfrom``. A ``)`` in it would end the
    comment early and a ``;`` would start a result of the sender's own, so
    whatever Google never writes is refused:

    * a backslash anywhere (Google doesn't escape);
    * a ``"`` anywhere but around one plain property value
      (``header.b="Pli4S9/s"``), so never in a comment;
    * a comment that holds ``(``, ``"``, ``;`` or a backslash, isn't right
      after its result's ``method=result``, is a result's second, sits in the
      authserv-id part, or never closes;
    * a ``)`` that closes nothing.

    Gmail prints the same sender in the comment and as ``smtp.mailfrom``. A
    ``;`` that splits the ``smtp.mailfrom`` copy is inside the comment copy,
    and a ``)`` that ends the comment copy early comes before any ``(`` in the
    ``smtp.mailfrom`` copy, so either way one of the two is refused.
    """
    segments: list[str] = []
    cur: list[str] = []
    commented = False        # this result already had its comment
    last = ""                # the last non-space character of this part
    i, n = 0, len(value)
    while i < n:
        ch = value[i]
        if ch in "\\)":
            return None
        if ch == '"':
            m = _QUOTED_VALUE_RE.match(value, i)
            end = m.end() if m else -1
            if last != "=" or end < 0:
                return None
            if end < n and not (value[end].isspace() or value[end] == ";"):
                return None
            cur.append(m.group(0))
            last = '"'
            i = end
            continue
        if ch == "(":
            end = _comment_end(value, i)
            if end < 0 or not segments or commented:
                return None
            if any(c in value[i + 1:end - 1] for c in '()"\\;'):
                return None
            if not _METHODSPEC_RE.fullmatch("".join(cur)):
                return None
            commented = True
            cur.append(" ")
            i = end
            continue
        if ch == ";":
            segments.append("".join(cur))
            cur, commented, last = [], False, ""
        else:
            cur.append(ch)
            if not ch.isspace():
                last = ch
        i += 1
    segments.append("".join(cur))
    return segments


def _unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] == '"':
        return re.sub(r"\\(.)", r"\1", value[1:-1])
    return value


def _segment_pairs(segment: str) -> list[tuple[str, str]] | None:
    """The ``key=value`` words of one result, in order: keys lowercased,
    whitespace around ``=`` allowed, quoted values unquoted. None when a word
    isn't ``key=value``: Google writes no bare words, so one is what is left
    of something the sender broke open."""
    words: list[str] = []
    cur: list[str] = []
    quoted = False
    escaped = False
    for ch in segment:
        if quoted:
            cur.append(ch)
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                quoted = False
        elif ch.isspace():
            if cur:
                words.append("".join(cur))
                cur = []
        else:
            if ch == '"':
                quoted = True
            cur.append(ch)
    if cur:
        words.append("".join(cur))

    merged: list[str] = []
    for w in words:
        if merged and (
            (w.startswith("=") and "=" not in merged[-1])
            or (merged[-1].endswith("=") and merged[-1].count("=") == 1
                and not merged[-1].startswith("=") and not w.startswith("="))
        ):
            merged[-1] += w
        else:
            merged.append(w)

    pairs: list[tuple[str, str]] = []
    for w in merged:
        key, eq, val = w.partition("=")
        if not (eq and key):
            return None
        pairs.append((key.lower(), _unquote(val)))
    return pairs


def _spf_identity_ok(r: _Result) -> bool:
    """Google's SPF result always names the identity it checked:
    ``smtp.mailfrom`` (one address), or ``smtp.helo`` for a bounce. One that
    names nothing, or a mailfrom that isn't an address, is what is left after
    the envelope sender closed the comment early or split the result."""
    mailfrom = r.prop("smtp.mailfrom")
    if mailfrom:
        local, at, _domain = mailfrom.rpartition("@")
        return bool(at and local and _bare_domain(mailfrom))
    return bool(mailfrom is not None and r.prop("smtp.helo"))


def _parse_auth_results(value: str) -> tuple[str, list[_Result]] | None:
    """An ``Authentication-Results`` value as ``(authserv-id, results)``;
    None when it doesn't parse, or isn't in the shape Google writes (see
    :func:`_split_auth_results`). Every part after the authserv-id must be a
    result (``method=result`` then properties), or the whole is ``none``; an
    ``spf`` result must name its identity (:func:`_spf_identity_ok`)."""
    segments = _split_auth_results(value)
    if segments is None:
        return None
    head = segments[0].split()
    authserv = head[0].lower() if head else ""
    if len(head) > 2 or (len(head) == 2 and not head[1].isdigit()):
        authserv = ""    # "authserv-id [version]" and nothing else
    parts = segments[1:]
    if len(parts) == 1 and parts[0].strip().lower() == "none":
        return authserv, []
    results: list[_Result] = []
    for seg in parts:
        pairs = _segment_pairs(seg)
        if not pairs or not _METHOD_RE.match(pairs[0][0]):
            return None
        result = pairs[0][1].strip().lower()
        if not _RESULT_RE.match(result):
            return None
        r = _Result(pairs[0][0].split("/", 1)[0], result, tuple(pairs[1:]))
        if r.method == "spf" and not _spf_identity_ok(r):
            return None
        results.append(r)
    return authserv, results


def _bare_domain(value: str) -> str:
    """``header.d`` / ``header.i`` / ``header.from`` as a lowercased domain
    ("" when it isn't one). ``header.i`` is ``[local]@domain``."""
    domain = value.rpartition("@")[2].strip().lower().rstrip(".")
    return domain if _DOMAIN_RE.match(domain) else ""


def _aligned(a: str, b: str) -> bool:
    """Relaxed alignment: the same domain, or one a subdomain of the other.
    ``evil-example.com`` is not aligned with ``example.com``."""
    return a == b or a.endswith("." + b) or b.endswith("." + a)


def _anchor_problem(above: list[tuple[str, str]]) -> str:
    """Why the headers *above* the topmost Authentication-Results (names
    lowercased, top-down) aren't Gmail's own delivery block; "" when they are.

    * ``no_google_mx_hop``: the last ``Received`` above it isn't Gmail's MX
      hop (``from … by mx.google.com with (E)SMTP(S) id …``), or something
      other than ``Received-SPF`` sits between the two;
    * ``auth_results_misplaced``: above the hop there is something Gmail
      doesn't write when it delivers (:data:`_GOOGLE_DELIVERY_HEADERS`), a
      ``Received`` other than Gmail's internal ``by … with SMTP id`` hop (a
      second MX hop, an HTTP or ESMTPSA submission), a second Return-Path, or
      a second Received-SPF.

    Gmail prepends its delivery block above every header the sender wrote.
    When Gmail wrote no Authentication-Results, whatever it did write (an
    internal hop, the submission's hop, DKIM signature and state headers) sits
    above a planted "Received … by mx.google.com" + Authentication-Results
    pair, and gives it away.
    """
    i = len(above) - 1
    while i >= 0 and above[i][0] == "received-spf":
        i -= 1
    if i < 0 or above[i][0] != "received" or not _MX_HOP_RE.match(above[i][1].strip()):
        return "no_google_mx_hop"
    if len(above) - 1 - i > 1:
        return "auth_results_misplaced"
    return_paths = 0
    for key, value in above[:i]:
        if key not in _GOOGLE_DELIVERY_HEADERS:
            return "auth_results_misplaced"
        if key == "received" and not _INTERNAL_HOP_RE.match(value.strip()):
            return "auth_results_misplaced"
        if key == "return-path":
            return_paths += 1
            if return_paths > 1:
                return "auth_results_misplaced"
    return ""


def _verdict(results: list[_Result], domain: str) -> tuple[bool, str]:
    for method in _SINGLE_METHODS:
        if sum(r.method == method for r in results) > 1:
            return False, "auth_results_ambiguous"    # Google writes one
    dmarc = [r for r in results if r.method == "dmarc"]
    if dmarc:
        r = dmarc[0]
        if r.result in _DMARC_FAILS:
            return False, f"dmarc_{r.result}"
        header_from = r.prop("header.from")
        if header_from is None:
            return False, "auth_results_ambiguous"
        hf = _bare_domain(header_from) if header_from else ""
        # Google names the domain whose policy it applied: the From domain,
        # or its organizational parent (From deck@auth.vendor.example passes
        # as header.from=vendor.example — seen on real Gmail headers).
        same_org = hf == domain or domain.endswith("." + hf)
        if header_from and not same_org:
            # Google read a different From domain than we did: trust neither.
            return False, "dmarc_domain_mismatch"
        if r.result == "pass" and hf and same_org:
            return True, "dmarc"
        # none, or a pass that names no domain: DKIM has to carry it.
    for r in results:
        if r.method != "dkim" or r.result != "pass":
            continue
        for key in ("header.d", "header.i"):
            v = r.prop(key)
            d = _bare_domain(v) if v else ""
            if d and _aligned(d, domain):
                return True, "dkim"
    return False, "no_aligned_dkim"


def sender_authenticated(inb: Inbound) -> tuple[bool, str]:
    """Check 6: whether Google vouches for the From domain, as
    ``(ok, reason)``.

    1. The **first** header named ``Authentication-Results`` (top-down,
       case-insensitive; ``ARC-Authentication-Results`` doesn't count) is the
       only one read. Gmail prepends its own above every header the sender
       wrote, so a lower one is the sender's and is never consulted.
    2. It must parse, in the shape Google writes it
       (:func:`_split_auth_results`): Gmail prints the envelope sender
       unescaped inside its SPF comment, so a quote, a backslash or a comment
       out of place means the sender is shaping the results.
    3. Its authserv-id must be ``mx.google.com``.
    4. It must close Gmail's own delivery block (:func:`_anchor_problem`):
       Gmail's MX hop the last ``Received`` above it, and nothing above that
       hop the sender could have written. This is the anchor for when Google
       wrote none and a planted one is the topmost.
    5. The envelope sender in that block's Return-Path, the one Google printed
       into the results, must be a plain address.
    6. DMARC ``pass`` for the From domain (or its organizational parent,
       which is what Google names for a subdomain sender) passes; ``fail``,
       ``temperror`` or ``permerror`` fails; a result for any other domain
       fails.
    7. With DMARC ``none`` or absent: a DKIM ``pass`` whose ``header.d`` (or
       ``header.i`` domain) is relaxed-aligned with the From domain passes.
    8. SPF alone never passes.

    On a pass ``reason`` is ``dmarc`` or ``dkim``. A failure is one of
    ``from_invalid``, ``no_auth_results``, ``auth_results_malformed``,
    ``auth_results_not_google``, ``no_google_mx_hop``,
    ``auth_results_misplaced``, ``envelope_sender_unsafe``,
    ``auth_results_ambiguous``, ``dmarc_fail`` / ``dmarc_temperror`` /
    ``dmarc_permerror``, ``dmarc_domain_mismatch``, ``no_aligned_dkim``,
    or ``auth_error`` (the check itself failed).
    """
    try:
        sender = sender_address(inb)
        domain = _bare_domain(sender) if sender else ""
        if not domain:
            return False, "from_invalid"
        above: list[tuple[str, str]] = []
        topmost: str | None = None
        for name, value in inb.headers:
            key = name.strip().lower()
            if key == "authentication-results":
                topmost = value
                break
            above.append((key, value))
        if topmost is None:
            return False, "no_auth_results"
        parsed = _parse_auth_results(topmost)
        if parsed is None:
            return False, "auth_results_malformed"
        authserv, results = parsed
        if authserv != GOOGLE_AUTHSERV_ID:
            return False, "auth_results_not_google"
        anchor = _anchor_problem(above)
        if anchor:
            return False, anchor
        if any(key == "return-path" and not _RETURN_PATH_RE.match(value.strip())
               for key, value in above):
            return False, "envelope_sender_unsafe"
        return _verdict(results, domain)
    except Exception:
        return False, "auth_error"
