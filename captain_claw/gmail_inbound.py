"""Inbound Gmail messages, read for the topic auto-reply. Pure.

Flight Deck's auto-reply engine fetches each new INBOX message with
``format=full`` and runs it through this module before any model sees it:

* :func:`parse_message` turns the Gmail API message into an :class:`Inbound`:
  the header block **in order, duplicates kept**, the addresses, the text body
  and the attachment names. Every older header parser here (``fetch_reply_context``,
  ``GoogleMailTool._parse_message``, ``poll_gmail``) builds a dict where the
  last value wins, so a header the sender planted lower down could override
  Google's. None of them is reused.
* :func:`prefilter` runs the design's deterministic checks 1–9 (labels, age,
  From, automated senders, auto-replies and lists, sender authentication,
  Reply-To, addressing, body size). The first one that fails names the
  ``skipped/<code>``, and no LLM has run yet. Checks 10 (caps) and 11 (human
  takeover) need the ledger and the thread, so they are the engine's.
* :func:`sender_authenticated` reads Google's own verdict on the From domain:
  DMARC, otherwise aligned DKIM. It reads only the **topmost**
  ``Authentication-Results`` header, only when it closes Gmail's own delivery
  block (Gmail's MX hop right above it, nothing the sender could write above
  that), and only in the exact shape Google writes it: Gmail prints the
  sender-chosen envelope sender unescaped inside it.

Standard library plus :mod:`captain_claw.gmail_compose`'s address helpers; no
Flight Deck imports. Nothing here raises. A message that can't be read fails
the check it can't pass, so it fails closed.
"""

